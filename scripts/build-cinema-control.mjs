/** Build the Stremio seek helper (scripts/android/CinemaControl.java) into a DEX and embed it in the Pi bridge.
 * Requires an existing JDK and Google's D8/R8 jar (same as build-cinema-metadata-probe.mjs). No device access.
 * Usage: node scripts/build-cinema-control.mjs --jdk=/path/to/jdk/Contents/Home --r8=/path/to/r8.jar
 * Writes home-assistant/custom_components/shoppinglist_cinema/control_dex.py (base64 + sha256).
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
const arg=name=>process.argv.find(v=>v.startsWith(`--${name}=`))?.split('=').slice(1).join('=');
const jdk=arg('jdk'),r8=arg('r8');if(!jdk||!r8)throw Error('Provide --jdk and --r8 paths');
const out=path.resolve('.cache/cinema-companion/android-control');
for(const folder of ['classes','dex'])await fs.mkdir(path.join(out,folder),{recursive:true});
for(const [binary,args] of [
 ['javac',['--release','8','-Xlint:-options','-d',path.join(out,'classes'),'scripts/android/CinemaControl.java']],
 ['java',['-cp',path.resolve(r8),'com.android.tools.r8.D8','--min-api','26','--output',path.join(out,'dex'),path.join(out,'classes/CinemaControl.class')]],
]){const r=spawnSync(path.join(jdk,'bin',binary),args,{stdio:'inherit'});if(r.status!==0)throw Error(`Build failed: ${binary}`);}
const dex=await fs.readFile(path.join(out,'dex/classes.dex'));
const sha=createHash('sha256').update(dex).digest('hex');
await fs.writeFile('home-assistant/custom_components/shoppinglist_cinema/control_dex.py',
 `"""Generated by scripts/build-cinema-control.mjs from scripts/android/CinemaControl.java. Do not edit."""\nDEX_SHA256 = '${sha}'\nDEX_BASE64 = '${dex.toString('base64')}'\n`);
console.log(`Seek helper: ${dex.length} bytes; SHA-256 ${sha}`);
