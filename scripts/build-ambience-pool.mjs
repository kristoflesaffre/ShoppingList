/**
 * Vaste keuze van ambience-video's per seizoen voor de lange druk op de SONOFF-knop (de Pi heeft geen YouTube-sleutel).
 * Zoekt met YOUTUBE_API_KEY op dezelfde zoekwoorden als het venster (src/lib/ambience-seasons.ts), houdt enkel lange
 * (≥ 1 u), niet-live video's over die buiten YouTube mogen spelen, en schrijft
 * home-assistant/custom_components/shoppinglist_cinema/ambience_pool.py. Niet vanzelf vernieuwd: opnieuw draaien als
 * video's verdwijnen.
 *
 *   node --env-file=.env.local scripts/build-ambience-pool.mjs
 */
import fs from "node:fs/promises";

const key = process.env.YOUTUBE_API_KEY;
if (!key) throw new Error("YOUTUBE_API_KEY ontbreekt");

const SEASONS = {
  kerst: "christmas ambience cozy fireplace",
  winter: "winter snow cabin ambience",
  lente: "spring nature ambience birds 4k",
  zomer: "summer evening ambience beach 4k",
  herfst: "autumn ambience cozy rain",
  halloween: "halloween ambience cozy",
};
const PER_SEASON = 10;

function seconds(iso) {
  const m = /^P(?:(\d+)D)?T?(?:(\d+)H)?(?:(\d+)M)?(?:(\d+)S)?$/.exec(iso ?? "");
  if (!m) return 0;
  return Number(m[1] ?? 0) * 86400 + Number(m[2] ?? 0) * 3600 + Number(m[3] ?? 0) * 60 + Number(m[4] ?? 0);
}

const pool = {};
for (const [season, q] of Object.entries(SEASONS)) {
  const search = await (await fetch(`https://www.googleapis.com/youtube/v3/search?${new URLSearchParams({ part: "snippet", type: "video", maxResults: "40", q, videoDuration: "long", videoEmbeddable: "true", safeSearch: "strict", regionCode: "BE", key })}`)).json();
  const ids = (search.items ?? []).map((i) => i.id?.videoId).filter(Boolean);
  const details = await (await fetch(`https://www.googleapis.com/youtube/v3/videos?${new URLSearchParams({ part: "contentDetails,status,snippet,statistics", id: ids.join(","), key })}`)).json();
  const good = (details.items ?? [])
    // Sfeerbeelden, geen muziekcompilaties of games.
    .filter((v) => !/minecraft|fortnite|top \d+|songs|lyrics|playlist|compilation|music video/i.test(v.snippet?.title ?? ""))
    .filter((v) => v.status?.embeddable && v.status?.privacyStatus === "public" && v.snippet?.liveBroadcastContent === "none" && seconds(v.contentDetails?.duration) >= 3600)
    .sort((a, b) => Number(b.statistics?.viewCount ?? 0) - Number(a.statistics?.viewCount ?? 0))
    .slice(0, PER_SEASON);
  pool[season] = good.map((v) => ({ id: v.id, title: v.snippet.title.slice(0, 80) }));
  console.log(`${season}: ${pool[season].length} video's`);
}

const lines = Object.entries(pool).map(([season, videos]) => `    '${season}': [\n${videos.map((v) => `        '${v.id}',  # ${v.title.replace(/[\\']/g, "")}`).join("\n")}\n    ],`);
await fs.writeFile(
  "home-assistant/custom_components/shoppinglist_cinema/ambience_pool.py",
  `"""Generated by scripts/build-ambience-pool.mjs (YouTube search, long + embeddable). Do not edit by hand."""\nPOOL = {\n${lines.join("\n")}\n}\n`,
);
